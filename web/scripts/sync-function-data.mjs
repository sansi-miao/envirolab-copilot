import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const webRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const projectRoot = resolve(webRoot, "..");
const seedPath = resolve(projectRoot, "data", "seeds", "experiments.json");
const outputPath = resolve(webRoot, "functions", "seed.ts");
const catalogPath = resolve(webRoot, "src", "data", "catalog.json");

export function syncFunctionData() {
  const seed = JSON.parse(readFileSync(seedPath, "utf8"));
  const source = [
    "// Generated by scripts/sync-function-data.mjs from data/seeds/experiments.json.",
    `export const seed = ${JSON.stringify(seed)};`,
    "",
  ].join("\n");
  writeFileSync(outputPath, source, "utf8");
  mkdirSync(dirname(catalogPath), { recursive: true });
  writeFileSync(catalogPath, `${JSON.stringify(seed, null, 2)}\n`, "utf8");
  return { experiments: seed.experiments.length, outputPath, catalogPath };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = syncFunctionData();
  console.log(
    `Synced ${result.experiments} experiments to ${result.outputPath} and ${result.catalogPath}`,
  );
}
